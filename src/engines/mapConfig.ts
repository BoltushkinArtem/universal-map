/**
 * Интерфейс конфигурации карты.
 * Описывает центр карты и уровень масштабирования (zoom).
 */
export interface MapConfig {
  /** Центр карты: долгота и широта */
  center: {
    /** Lng / longitude — долгота точки на карте */
    lng: number;

    /** Lat / latitude — широта точки на карте */
    lat: number;
  };

  /** Масштаб карты. Чем больше значение, тем ближе приближение */
  zoom: number;
}
